#List Example
fruits = ["Apple", "Banana", "Mango"]

print(fruits)
print(fruits[0])


#Adding items
fruits.append("Orange")

print(fruits)


#Removing Items
fruits.remove("Banana")

print(fruits)


#Tuples

colors = ("Red", "Green", "Blue")

print(colors)
print(colors[1])

#Dictionary Example
student = {
    "name": "Man",
    "age": 20,
    "course": "Python"
}

print(student)
print(student["name"])

#Adding New Data
student["city"] = "Ahmedabad"

print(student)

#Updating New Data
student["age"] = 21

print(student)
